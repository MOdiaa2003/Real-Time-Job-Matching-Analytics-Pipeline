# tests/run_all.ps1 - run every acceptance suite sequentially and write
# tests/RESULTS.md. Exits nonzero if any suite failed.
$repo = Split-Path -Parent (Split-Path -Parent $MyInvocation.MyCommand.Path)
$suites = @(
    "01_pipeline_health",
    "02_dedup_dlq_integrity",
    "03_job_state_invalidation",
    "04_windowed_metrics",
    "05_jdbc_sink_upsert",
    "06_latency_freshness"
)

New-Item -ItemType Directory -Force -Path (Join-Path $repo "tests") | Out-Null
$resultsPath = Join-Path $repo "tests\RESULTS.md"
$summary = @()
$failed = 0
$start = Get-Date
$stamp = $start.ToString("yyyy-MM-dd HH:mm:ss")

foreach ($s in $suites) {
    Write-Host ""
    Write-Host ("== running {0} ..." -f $s)
    $suiteStart = Get-Date
    & powershell -ExecutionPolicy Bypass -File (Join-Path $repo "tests\$s\run.ps1") 2>&1 |
        Select-Object -Last 30
    $code = $LASTEXITCODE
    $dir = Join-Path $repo "tests\$s"
    $runFile = Join-Path $dir "results\last_run.txt"
    $detail = "."
    if (Test-Path $runFile) {
        $detail = (Get-Content $runFile | Select-Object -First 2) -join "`n"
        $detail = $detail -replace "`n", "`n$($s)| "
    }
    $verdict = "FAIL"
    if ($code -eq 0) { $verdict = "PASS" } else { $failed++ }
    $summary += "| $s | $verdict | $([int]((Get-Date) - $suiteStart).TotalSeconds)s |"
}
$rows = ($summary -join "`n") + "`n"
$md = @"
# Acceptance test results

Run started: $stamp - generated by tests\run_all.ps1 after the sequential run; per-suite receipts live under tests\<suite>\results\.

| Suite | Verdict | Wall time |
|-------|---------|-----------|
$rows
Total FAILed suites: $failed / $($suites.Count)

"@
Set-Content -Path $resultsPath -Value $md
Write-Host ""
Write-Host ($md -join "`n")
exit $(if ($failed -gt 0) { 1 } else { 0 })
